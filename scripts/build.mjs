import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));

// The Harness supplies React via the lazy factory's require parameter. Bundle
// ArtPlayer/HLS locally, never ship another React or depend on a global UMD copy.
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client.jsx'],
  bundle: true,
  write: false,
  minify: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', 'react/jsx-dev-runtime'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  // Import CSS as a string and render it from the owned React component/effect.
  // No unowned stylesheet or global DOM write is added by this build wrapper.
  loader: { '.css': 'text', '.svg': 'text' },
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'inline',
  logLevel: 'info',
});

if (result.outputFiles.length !== 1) {
  throw new Error('Expected exactly one browser JavaScript artifact.');
}
const output = [
  '// Generated by scripts/build.mjs; do not edit.',
  `window.__ModuleLoader__.load({id:${JSON.stringify(manifest.name)},factory(require){`,
  'const module = { exports: {} };',
  'const exports = module.exports;',
  result.outputFiles[0].text,
  'return module.exports;',
  '}});',
  '',
].join('\n');
await mkdir(path.join(root, 'dist'), { recursive: true });
await writeFile(path.join(root, 'dist/client.js'), output);
console.log(`Built ${manifest.name}@${manifest.version}: dist/client.js`);
